const devMarks: Array<[string, string]> = [
  [" 开发环境验证链接：", " Dev verification link: "],
  [" 开发环境重置链接：", " Dev reset link: "],
];

type Key = keyof typeof zh;
type I18nValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: Key, values?: Record<string, string | number>) => string;
  tr: (message: string) => string;
  planName: (code: string, fallback?: string) => string;
  dateLocale: string;
};

const I18nContext = createContext<I18nValue | null>(null);
const storageKey = "huijian.locale";

function initialLocale(): Locale {
  try {
    const saved = localStorage.getItem(storageKey);
    if (saved === "zh" || saved === "en") return saved;
  } catch {
    /* private mode */
  }
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

function fill(template: string, values?: Record<string, string | number>): string {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ""));
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale);

  function setLocale(next: Locale) {
    setLocaleState(next);
    try {
      localStorage.setItem(storageKey, next);
    } catch {
      /* ignore */
    }
  }

  useEffect(() => {
    const pack = locale === "zh" ? zh : en;
    document.documentElement.lang = locale === "zh" ? "zh-CN" : "en";
    document.title = pack.title;
    document.querySelector('meta[name="description"]')?.setAttribute("content", pack.description);
  }, [locale]);

  const value = useMemo<I18nValue>(() => {
    const pack = locale === "zh" ? zh : en;
    return {
      locale,
      setLocale,
      t: (key, values) => fill(pack[key], values),
      tr: (message) => {
        if (!message || locale === "zh") return message;
        for (const [mark, replacement] of devMarks) {
          const index = message.indexOf(mark);
          if (index >= 0) {
            const head = message.slice(0, index);
            return `${serverEn[head] ?? head}${replacement}${message.slice(index + mark.length)}`;
          }
        }
        return serverEn[message] ?? message;
      },
      planName: (code, fallback) => {
        if (code === "free") return pack.planFreeName;
        if (code === "launch") return pack.planLaunchName;
        if (code === "monthly") return pack.planMonthlyName;
        return fallback || code;
      },
      dateLocale: locale === "zh" ? "zh-CN" : "en-US",
    };
  }, [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("LocaleProvider missing");
  return value;
}
